import { ChevronRight } from "lucide-react";
import type { ReactNode } from "react";

import { SectionHeader } from "@/components/layout/section-header";
import { Card } from "@/components/ui/card";
import { formatAbsoluteTimestamp } from "@/lib/datetime";
import { forecastRoundingLabel } from "@/lib/forecast";
import { formatMonth } from "@/lib/money";
import { cn } from "@/lib/utils";
import type { ForecastAccuracy } from "@/types/api";

function Row({ term, children, className }: { term: string; children: ReactNode; className?: string }) {
  return (
    <div className={cn("grid content-start gap-1", className)}>
      <dt className="text-muted-foreground text-xs font-medium">{term}</dt>
      <dd className="min-w-0 text-sm leading-6">{children}</dd>
    </div>
  );
}

/** How the API compared saved forecasts with actual revenue, shown as returned. */
export function ForecastAccuracyMethodology({ accuracy }: { accuracy: ForecastAccuracy }) {
  return (
    <section className="grid gap-3" aria-labelledby="forecast-accuracy-methodology-heading">
      <SectionHeader
        id="forecast-accuracy-methodology-heading"
        title="Methodology and assumptions"
        description="Calculated by FlowPilot from forecasts saved each day and from closed won deals. Not generated by AI; past forecasts are never recalculated."
      />
      <Card className="grid gap-5 p-4 sm:p-5">
        <dl className="grid gap-x-8 gap-y-4 sm:grid-cols-2 lg:grid-cols-3">
          <Row term="Currency">{accuracy.currency}</Row>
          <Row term="As of">{formatAbsoluteTimestamp(accuracy.as_of) ?? accuracy.as_of}</Row>
          <Row term="Range">
            {formatMonth(accuracy.from_month)} – {formatMonth(accuracy.to_month)} (UTC months)
          </Row>
          <Row term="Accuracy" className="sm:col-span-2 lg:col-span-3">
            1 − |actual − forecast| ÷ actual, as a percentage. 100% is an exact forecast; it falls
            as the error grows and becomes negative once the error is larger than the revenue
            actually won. Not shown when no revenue was won.
          </Row>
          <Row term="Weighted accuracy" className="sm:col-span-2 lg:col-span-3">
            Over the compared months combined: 1 − Σ|actual − forecast| ÷ Σactual. Large months
            count for more than small ones; monthly percentages are never averaged.
          </Row>
          <Row term="Variance">
            Actual − forecast. Positive means more was won than forecast; the percentage is of
            the forecast and is not shown when the forecast was 0.
          </Row>
          <Row term="Saved forecast used">
            The latest daily snapshot captured up to {accuracy.snapshot_tolerance_days} days before
            the cutoff: 00:00 UTC on the month&apos;s first day minus the lead time. At month start
            the snapshot must be captured before midnight.
          </Row>
          <Row term="Rounding">
            {forecastRoundingLabel(accuracy.rounding)} Percentages are rounded half away from zero
            to one decimal.
          </Row>
        </dl>
        {/* Native disclosure: keyboard and screen-reader support without extra state. */}
        <details className="group border-border border-t pt-4">
          <summary className="focus-visible:ring-ring flex w-fit cursor-pointer list-none items-center gap-1.5 rounded-sm text-sm font-medium outline-none focus-visible:ring-2 [&::-webkit-details-marker]:hidden">
            <ChevronRight
              className="text-muted-foreground size-4 transition-transform group-open:rotate-90 motion-reduce:transition-none"
              aria-hidden="true"
            />
            Assumptions ({accuracy.assumptions.length})
          </summary>
          <ul className="text-muted-foreground mt-3 grid list-disc gap-1.5 pl-10 text-sm leading-6">
            {accuracy.assumptions.map((assumption) => (
              <li key={assumption.code} data-code={assumption.code}>
                {assumption.detail}
              </li>
            ))}
          </ul>
        </details>
      </Card>
    </section>
  );
}
