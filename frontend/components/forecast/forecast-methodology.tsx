import { ChevronRight } from "lucide-react";
import type { ReactNode } from "react";

import { SectionHeader } from "@/components/layout/section-header";
import { Card } from "@/components/ui/card";
import { formatAbsoluteTimestamp } from "@/lib/datetime";
import { DEAL_STAGE_LABELS, isClosedStage } from "@/lib/deals";
import {
  forecastHorizonLabel,
  forecastMethodLabel,
  forecastRoundingLabel,
} from "@/lib/forecast";
import { formatDateOnly } from "@/lib/money";
import { cn } from "@/lib/utils";
import type { PipelineForecast } from "@/types/api";

function Row({ term, children, className }: { term: string; children: ReactNode; className?: string }) {
  return (
    <div className={cn("grid content-start gap-1", className)}>
      <dt className="text-muted-foreground text-xs font-medium">{term}</dt>
      <dd className="min-w-0 text-sm">{children}</dd>
    </div>
  );
}

/** How the API produced the figures, shown as returned, including its limitations. */
export function ForecastMethodology({ forecast }: { forecast: PipelineForecast }) {
  const openStages = forecast.stage_probabilities.filter((row) => !isClosedStage(row.stage));
  return (
    <section className="grid gap-3" aria-labelledby="forecast-methodology-heading">
      <SectionHeader
        id="forecast-methodology-heading"
        title="Methodology and assumptions"
        description="Calculated from saved deals by FlowPilot. Not generated by AI and not calibrated against past results."
      />
      <Card className="grid gap-5 p-4 sm:p-5">
        <dl className="grid gap-x-8 gap-y-4 sm:grid-cols-2 lg:grid-cols-3">
          <Row term="Currency">{forecast.currency}</Row>
          <Row term="As of">{formatAbsoluteTimestamp(forecast.as_of) ?? forecast.as_of}</Row>
          <Row term="Method">{forecastMethodLabel(forecast.method)}</Row>
          <Row term="Horizon">
            {formatDateOnly(forecast.horizon_start)} – {formatDateOnly(forecast.horizon_end)} (
            {forecastHorizonLabel(forecast.granularity, forecast.periods.length)})
          </Row>
          <Row term="Rounding" className="sm:col-span-2 lg:col-span-2">
            {forecastRoundingLabel(forecast.rounding)}
          </Row>
          <Row term="Stage probabilities" className="sm:col-span-2 lg:col-span-3">
            <ul className="flex flex-wrap gap-x-4 gap-y-1">
              {openStages.map((row) => (
                <li key={row.stage} className="tabular-nums">
                  {DEAL_STAGE_LABELS[row.stage]} {row.default_probability}%
                </li>
              ))}
            </ul>
          </Row>
        </dl>
        {/* Native disclosure: keyboard and screen-reader support without extra state. */}
        <details className="group border-border border-t pt-4">
          <summary className="focus-visible:ring-ring flex w-fit cursor-pointer list-none items-center gap-1.5 rounded-sm text-sm font-medium outline-none focus-visible:ring-2 [&::-webkit-details-marker]:hidden">
            <ChevronRight
              className="text-muted-foreground size-4 transition-transform group-open:rotate-90 motion-reduce:transition-none"
              aria-hidden="true"
            />
            Assumptions ({forecast.assumptions.length})
          </summary>
          <ul className="text-muted-foreground mt-3 grid list-disc gap-1.5 pl-10 text-sm leading-6">
            {forecast.assumptions.map((assumption) => (
              <li key={assumption.code} data-code={assumption.code}>
                {assumption.detail}
              </li>
            ))}
          </ul>
        </details>
      </Card>
    </section>
  );
}
